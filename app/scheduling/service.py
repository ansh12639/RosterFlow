"""Roster lifecycle operations (generate, edit, validate, publish, re-plan, impact).

Every mutating operation finishes with ``revalidate`` so conflicts shown to the
manager always reflect the roster *and* the current configuration.
"""
from __future__ import annotations

import json
from copy import deepcopy
from datetime import date, datetime, timedelta

from sqlalchemy import func, insert

from app.extensions import db
from app.models import (Conflict, RosterChangeLog, RosterDay, RosterEntry, RosterVersion)
from .engine import RosterEngine
from .loader import load_scenario
from .plan import Cover, DayState, Plan, coverage, entries_for
from .scenario import ABSENCE_STATUS, STATUS_LABEL, WORKING
from .validator import cover_candidates, validate


class RosterError(ValueError):
    """Business-rule error shown to the user."""


# --------------------------------------------------------------------- helpers
def scenario_for(version):
    return load_scenario(version.roster_month.year, version.roster_month.month)


def load_plan(version):
    plan = Plan()
    for d in RosterDay.query.filter_by(roster_version_id=version.id).all():
        plan.status[(d.employee_id, d.roster_date)] = DayState(d.status, d.source, d.note or "")
    for e in RosterEntry.query.filter_by(roster_version_id=version.id, is_cover=True).all():
        plan.covers.append(Cover(e.employee_id, e.brand_id, e.process_id, e.roster_date, e.source))
    return plan


def _log(version, action, description):
    db.session.add(RosterChangeLog(roster_version_id=version.id, action=action, description=description))


def _write_days(version, plan):
    RosterDay.query.filter_by(roster_version_id=version.id).delete()
    rows = [dict(roster_version_id=version.id, employee_id=e, roster_date=d, status=s.status,
                 source=s.source, note=(s.note or None) and s.note[:255])
            for (e, d), s in plan.status.items()]
    if rows:
        db.session.execute(insert(RosterDay), rows)


def _write_entries_and_conflicts(version, sc, plan):
    RosterEntry.query.filter_by(roster_version_id=version.id).delete()
    rows = [dict(roster_version_id=version.id, **r) for r in entries_for(sc, plan)]
    if rows:
        db.session.execute(insert(RosterEntry), rows)

    acknowledged = {c.key for c in Conflict.query.filter_by(roster_version_id=version.id, resolved=True).all()}
    Conflict.query.filter_by(roster_version_id=version.id).delete()
    conflicts = validate(sc, plan)
    crows = []
    for c in conflicts:
        key = (c["conflict_type"], c["roster_date"], c["brand_id"], c["process_id"], c["employee_id"])
        crows.append(dict(
            roster_version_id=version.id, roster_date=c["roster_date"], brand_id=c["brand_id"],
            process_id=c["process_id"], employee_id=c["employee_id"], conflict_type=c["conflict_type"],
            severity=c["severity"], required_staff=c["required_staff"], available_staff=c["available_staff"],
            message=c["message"], suggestion=c["suggestion"],
            candidates_json=json.dumps(c["candidates"]) if c["candidates"] else None,
            resolved=key in acknowledged, created_at=datetime.utcnow(),
        ))
    if crows:
        db.session.execute(insert(Conflict), crows)
    return conflicts


def conflict_counts(version_id):
    rows = (db.session.query(Conflict.severity, Conflict.resolved, func.count())
            .filter(Conflict.roster_version_id == version_id)
            .group_by(Conflict.severity, Conflict.resolved).all())
    counts = dict(errors=0, open_errors=0, warnings=0, info=0)
    for severity, resolved, n in rows:
        if severity == "ERROR":
            counts["errors"] += n
            if not resolved:
                counts["open_errors"] += n
        elif severity == "WARNING":
            counts["warnings"] += n
        else:
            counts["info"] += n
    return counts


def _require_draft(version):
    if not version.editable:
        raise RosterError("Only DRAFT rosters can be edited. Create a revision of this roster first.")


# --------------------------------------------------------------------- lifecycle
def _new_version(month_start, notes, parent=None):
    latest = (db.session.query(func.max(RosterVersion.version_number))
              .filter(RosterVersion.roster_month == month_start).scalar())
    version = RosterVersion(roster_month=month_start, version_number=(latest or 0) + 1, status="DRAFT",
                            notes=notes, parent_version_id=parent.id if parent else None)
    db.session.add(version)
    db.session.flush()
    return version


def generate_roster(year, month, notes="Generated by scheduling engine"):
    sc = load_scenario(year, month)
    plan = RosterEngine(sc).generate()
    version = _new_version(date(year, month, 1), notes)
    _write_days(version, plan)
    _write_entries_and_conflicts(version, sc, plan)
    _log(version, "GENERATE", f"Generated for {len(sc.active_employees)} employees, "
                              f"{len(sc.pairs)} brand/process scopes, {len(plan.covers)} backup covers.")
    db.session.commit()
    return version


def revalidate(version, commit=True):
    sc = scenario_for(version)
    conflicts = _write_entries_and_conflicts(version, sc, load_plan(version))
    if commit:
        db.session.commit()
    return conflicts


def set_day_status(version, employee_id, day, status, note=""):
    _require_draft(version)
    plan = load_plan(version)
    key = (employee_id, day)
    if key not in plan.status:
        raise RosterError("That employee/date is not part of this roster.")
    before = plan.status[key].status
    plan.status[key] = DayState(status, "MANUAL", note or "Manual change")
    removed = [c for c in plan.covers if c.employee_id == employee_id and c.day == day]
    if status != WORKING:
        plan.covers = [c for c in plan.covers if c not in removed]
    _write_days(version, plan)
    sc = scenario_for(version)
    _write_entries_and_conflicts(version, sc, plan)  # entries are re-derived, so removed covers disappear
    _log(version, "EDIT_DAY", f"{sc.emp_name(employee_id)} on {day:%d %b}: "
                              f"{STATUS_LABEL.get(before, before)} → {STATUS_LABEL.get(status, status)}"
                              f"{' (removed ' + str(len(removed)) + ' cover)' if status != WORKING and removed else ''}"
                              f"{'. Note: ' + note if note else ''}")
    db.session.commit()


def add_cover(version, employee_id, brand_id, process_id, day, source="MANUAL"):
    _require_draft(version)
    plan = load_plan(version)
    sc = scenario_for(version)
    if not plan.is_working(employee_id, day):
        raise RosterError(f"{sc.emp_name(employee_id)} is not working on {day:%d %b}; mark them working first.")
    if any(c.employee_id == employee_id and c.brand_id == brand_id and c.process_id == process_id and c.day == day
           for c in plan.covers):
        raise RosterError("That cover already exists.")
    plan.covers.append(Cover(employee_id, brand_id, process_id, day, source))
    _write_entries_and_conflicts(version, sc, plan)
    _log(version, "ADD_COVER", f"{sc.emp_name(employee_id)} covers {sc.scope_name(brand_id, process_id)} on {day:%d %b}.")
    db.session.commit()


def remove_cover(version, entry_id):
    _require_draft(version)
    entry = RosterEntry.query.filter_by(id=entry_id, roster_version_id=version.id, is_cover=True).first()
    if not entry:
        raise RosterError("Cover not found.")
    description = f"Removed cover: {entry.employee.full_name} for {entry.brand.name} / {entry.process.name} on {entry.roster_date:%d %b}."
    db.session.delete(entry)
    db.session.flush()
    revalidate(version, commit=False)
    _log(version, "REMOVE_COVER", description)
    db.session.commit()


def auto_assign_covers(version):
    """Apply the top-ranked compatible candidate to every open coverage gap."""
    _require_draft(version)
    sc = scenario_for(version)
    plan = load_plan(version)
    applied = []
    for c in validate(sc, plan):
        if c["conflict_type"] != "COVERAGE_GAP":
            continue
        b, p, d = c["brand_id"], c["process_id"], c["roster_date"]
        need = c["required_staff"] - c["available_staff"]
        while need > 0:
            cands = cover_candidates(sc, plan, b, p, d, limit=1)
            if not cands:
                break
            plan.covers.append(Cover(cands[0]["employee_id"], b, p, d, "MANUAL"))
            applied.append(f"{cands[0]['name']} → {sc.scope_name(b, p)} {d:%d %b}")
            need -= 1
    if applied:
        _write_entries_and_conflicts(version, sc, plan)
        _log(version, "AUTO_COVER", f"Applied {len(applied)} suggested cover(s): " + "; ".join(applied[:20])
             + (" …" if len(applied) > 20 else ""))
        db.session.commit()
    return applied


def publish(version, acknowledge_errors=False):
    if version.status != "DRAFT":
        raise RosterError("Only a DRAFT roster can be published.")
    revalidate(version, commit=False)
    open_errors = Conflict.query.filter_by(roster_version_id=version.id, severity="ERROR", resolved=False).count()
    if open_errors and not acknowledge_errors:
        raise RosterError(f"{open_errors} unresolved error(s) remain. Resolve them, or tick "
                          "'I accept the open error(s)' to publish with the risk explicitly acknowledged.")
    if open_errors:
        Conflict.query.filter_by(roster_version_id=version.id, severity="ERROR", resolved=False).update({"resolved": True})
    RosterVersion.query.filter(RosterVersion.roster_month == version.roster_month,
                               RosterVersion.status == "PUBLISHED").update({"status": "ARCHIVED"})
    version.status = "PUBLISHED"
    version.published_at = datetime.utcnow()
    _log(version, "PUBLISH", "Published" + (f" with {open_errors} acknowledged error(s)." if open_errors else " with no open errors."))
    db.session.commit()


def create_revision(version, reason="Revision"):
    """Copy a roster into a new DRAFT (published rosters are never edited in place)."""
    new = _new_version(version.roster_month, f"{reason} of V{version.version_number}", parent=version)
    plan = load_plan(version)
    _write_days(new, plan)
    _write_entries_and_conflicts(new, scenario_for(new), plan)
    _log(new, "REVISION", f"Created from V{version.version_number} ({version.status}). {reason}.")
    db.session.commit()
    return new


def reoptimise(version, from_date):
    """Regenerate the roster from ``from_date`` onwards as a new version.

    Days before ``from_date`` and all MANUAL edits are locked, so already-worked
    days and the manager's decisions are preserved; only the rest is re-planned
    against the latest leave, availability and rules.
    """
    sc = scenario_for(version)
    old = load_plan(version)
    locked = {k: v for k, v in old.status.items() if k[1] < from_date or v.source == "MANUAL"}
    keep = [c for c in old.covers if c.day < from_date or c.source == "MANUAL"]
    plan = RosterEngine(sc).generate(locked=locked, keep_covers=keep)
    new = _new_version(version.roster_month, f"Re-optimised from {from_date:%d %b} (based on V{version.version_number})",
                       parent=version)
    _write_days(new, plan)
    _write_entries_and_conflicts(new, sc, plan)
    _log(new, "REOPTIMISE", f"Re-planned {from_date:%d %b} onwards; {len(locked)} cells locked (past days + manual edits).")
    db.session.commit()
    return new


def delete_version(version):
    if version.status == "PUBLISHED":
        raise RosterError("A published roster cannot be deleted; publish a revision instead.")
    db.session.delete(version)
    db.session.commit()


def acknowledge(conflict, value=True):
    conflict.resolved = value
    _log(conflict.version, "ACKNOWLEDGE", f"{'Acknowledged' if value else 'Re-opened'}: {conflict.message[:180]}")
    db.session.commit()


# --------------------------------------------------------------------- change impact
def impact_of_absence(version, employee_id, start, end, kind="UNAVAILABLE"):
    """What happens to coverage if an employee is away from ``start`` to ``end``?

    Returns one row per affected duty, saying whether the remaining staff can
    absorb it and, if not, who could cover.
    """
    sc = scenario_for(version)
    plan = load_plan(version)
    after = deepcopy(plan)
    status = ABSENCE_STATUS.get(kind, "UNAVAILABLE")
    days = [d for d in sc.days if start <= d <= end]
    lost_covers = [c for c in plan.covers if c.employee_id == employee_id and c.day in days]
    for d in days:
        if (employee_id, d) in after.status:
            after.status[(employee_id, d)] = DayState(status, "MANUAL", "What-if")
    after.covers = [c for c in after.covers if c not in lost_covers]
    covers_after = after.covers_by_scope()

    rows = []
    for d in days:
        duties = sc.duties(employee_id, d) if plan.is_working(employee_id, d) else []
        duties = list(duties) + [(c.brand_id, c.process_id) for c in lost_covers if c.day == d]
        for b, p in duties:
            need = sc.demand(b, p, d)
            working, covers = coverage(sc, after, b, p, d, covers_after)
            have = len(working) + len(covers)
            rows.append(dict(
                day=d, brand_id=b, process_id=p, scope=sc.scope_name(b, p), need=need, have=have,
                ok=have >= need, others=[sc.emp_name(e) for e in working + covers],
                candidates=[] if have >= need else cover_candidates(sc, after, b, p, d),
                single=len(sc.primaries(b, p, d)) == 1,
            ))
    brands_hit = {}
    for r in rows:
        if not r["ok"]:
            brands_hit.setdefault(r["day"], set()).add(sc.brand_names.get(r["brand_id"]))
    working_days = [d for d in days if plan.is_working(employee_id, d)]
    return dict(employee=sc.emp_name(employee_id), rows=rows, working_days=working_days,
                gaps=sum(1 for r in rows if not r["ok"]), absorbed=sum(1 for r in rows if r["ok"]),
                multi_brand_days={d: sorted(v) for d, v in brands_hit.items() if len(v) > 1})


def apply_absence(version, employee_id, start, end, kind, note):
    """Write an absence into a roster; published rosters get a new DRAFT revision."""
    target = version if version.editable else create_revision(version, "Change after publication")
    plan = load_plan(target)
    sc = scenario_for(target)
    status = ABSENCE_STATUS.get(kind, "UNAVAILABLE")
    changed = 0
    for d in sc.days:
        if start <= d <= end and (employee_id, d) in plan.status:
            plan.status[(employee_id, d)] = DayState(status, "MANUAL", note or STATUS_LABEL[status])
            changed += 1
    plan.covers = [c for c in plan.covers if not (c.employee_id == employee_id and start <= c.day <= end)]
    _write_days(target, plan)
    _write_entries_and_conflicts(target, sc, plan)
    _log(target, "ABSENCE", f"{sc.emp_name(employee_id)} marked {STATUS_LABEL[status].lower()} "
                            f"{start:%d %b}–{end:%d %b} ({changed} day(s)).")
    db.session.commit()
    return target


def compare_versions(a, b):
    """Cells whose status differs between two versions of the same month."""
    pa, pb = load_plan(a), load_plan(b)
    diffs = []
    for key in sorted(set(pa.status) | set(pb.status), key=lambda k: (k[1], k[0])):
        sa, sb = pa.status.get(key), pb.status.get(key)
        if (sa and sa.status) != (sb and sb.status):
            diffs.append(dict(employee_id=key[0], day=key[1], before=sa.status if sa else None,
                              after=sb.status if sb else None))
    cov_a = {(c.employee_id, c.brand_id, c.process_id, c.day) for c in pa.covers}
    cov_b = {(c.employee_id, c.brand_id, c.process_id, c.day) for c in pb.covers}
    return dict(day_changes=diffs, covers_added=sorted(cov_b - cov_a, key=lambda x: x[3]),
                covers_removed=sorted(cov_a - cov_b, key=lambda x: x[3]))


def latest_version_for(day):
    month = date(day.year, day.month, 1)
    return (RosterVersion.query.filter(RosterVersion.roster_month == month, RosterVersion.status != "ARCHIVED")
            .order_by((RosterVersion.status == "PUBLISHED").desc(), RosterVersion.version_number.desc()).first())
